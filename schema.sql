CREATE TABLE songs (
    song_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR2(100) NOT NULL,
    artist VARCHAR2(100) NOT NULL,
    album VARCHAR2(100),
    publication_year NUMBER(4) NOT NULL,
    upload_date TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE stanzas (
    stanza_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    song_id NUMBER NOT NULL,
    stanza_number NUMBER NOT NULL,
    CONSTRAINT pk_stanzas
        PRIMARY KEY (stanza_id),
    CONSTRAINT fk_stanzas_song
        FOREIGN KEY (song_id)
        REFERENCES songs(song_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_stanzas_number
        CHECK (stanza_number > 0),
    CONSTRAINT uq_stanzas_song_number
        UNIQUE (song_id, stanza_number)
);

CREATE TABLE words (
    word_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    text VARCHAR2(100) NOT NULL,
    CONSTRAINT pk_words
        PRIMARY KEY (word_id),
    CONSTRAINT uq_words_text
        UNIQUE (text)
);

CREATE TABLE word_occurrences (
    occurrence_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    word_id NUMBER NOT NULL,
    song_id NUMBER NOT NULL,
    stanza_id NUMBER NOT NULL,
    global_line_number NUMBER NOT NULL,
    line_number_in_stanza NUMBER NOT NULL,
    position_in_line NUMBER NOT NULL,
    position_in_song NUMBER NOT NULL,
    original_token VARCHAR2(300) NOT NULL,
    CONSTRAINT fk_word_occurrences_word
        FOREIGN KEY (word_id)
        REFERENCES words (word_id),
    CONSTRAINT fk_word_occurrences_song
        FOREIGN KEY (song_id)
        REFERENCES songs (song_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_word_occurrences_stanza
        FOREIGN KEY (stanza_id)
        REFERENCES stanzas (stanza_id)
        ON DELETE CASCADE,
    CONSTRAINT chk_word_occurrences_global_line
        CHECK (global_line_number > 0),
    CONSTRAINT chk_word_occurrences_local_line
        CHECK (line_number_in_stanza > 0),
    CONSTRAINT chk_word_occurrences_position_line
        CHECK (position_in_line > 0),
    CONSTRAINT chk_word_occurrences_position_song
        CHECK (position_in_song > 0),
    CONSTRAINT uq_word_occurrences_song_position
        UNIQUE (song_id, position_in_song)
);

CREATE TABLE word_groups (
    group_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    group_name VARCHAR2(100) NOT NULL,
    description VARCHAR2(500),
    creation_date TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,
    CONSTRAINT pk_word_groups
        PRIMARY KEY (group_id),
    CONSTRAINT uq_word_groups_name
        UNIQUE (group_name)
);

CREATE TABLE group_words (
    group_id NUMBER NOT NULL,
    word_id NUMBER NOT NULL,
    CONSTRAINT pk_group_words
        PRIMARY KEY (group_id, word_id),
    CONSTRAINT fk_group_words_group
        FOREIGN KEY (group_id)
        REFERENCES word_groups (group_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_group_words_word
        FOREIGN KEY (word_id)
        REFERENCES words (word_id)
        ON DELETE CASCADE
);

CREATE TABLE phrases (
    phrase_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    phrase_name VARCHAR2(200) NOT NULL,
    phrase_text VARCHAR2(1000) NOT NULL,
    creation_date TIMESTAMP WITH TIME ZONE
        DEFAULT CURRENT_TIMESTAMP
        NOT NULL,
    CONSTRAINT pk_phrases
        PRIMARY KEY (phrase_id),
    CONSTRAINT uq_phrases_name
        UNIQUE (phrase_name)
);

CREATE TABLE phrase_occurrences (
    phrase_occurrence_id NUMBER GENERATED BY DEFAULT AS IDENTITY,
    phrase_id NUMBER NOT NULL,
    song_id NUMBER NOT NULL,
    start_occurrence_id NUMBER NOT NULL,
    end_occurrence_id NUMBER NOT NULL,
    CONSTRAINT pk_phrase_occurrences
        PRIMARY KEY (phrase_occurrence_id),
    CONSTRAINT fk_phrase_occurrences_phrase
        FOREIGN KEY (phrase_id)
        REFERENCES phrases (phrase_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_phrase_occurrences_song
        FOREIGN KEY (song_id)
        REFERENCES songs (song_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_phrase_occurrences_start
        FOREIGN KEY (start_occurrence_id)
        REFERENCES word_occurrences (occurrence_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_phrase_occurrences_end
        FOREIGN KEY (end_occurrence_id)
        REFERENCES word_occurrences (occurrence_id)
        ON DELETE CASCADE,
    CONSTRAINT uq_phrase_occurrences_location
        UNIQUE (
            phrase_id,
            song_id,
            start_occurrence_id,
            end_occurrence_id
        )
);

CREATE INDEX ix_word_occurrences_word
    ON word_occurrences (word_id);

CREATE INDEX ix_word_occurrences_song_line
    ON word_occurrences (
        song_id,
        global_line_number,
        position_in_line
    );

CREATE INDEX ix_word_occurrences_stanza
    ON word_occurrences (stanza_id);

CREATE INDEX ix_group_words_word
    ON group_words (word_id);

CREATE INDEX ix_phrase_occurrences_song
    ON phrase_occurrences (song_id);
